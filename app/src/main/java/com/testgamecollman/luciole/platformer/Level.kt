/**
 * Niveau en tuiles : '#' bloc, '=' passerelle (on la traverse par dessous),
 * '^' pointes, 'o' rouage, 'S' départ, 'D' porte de sortie,
 * 'E' robot patrouilleur, 'V' drone volant, '.' vide.
 */
class Level(src: List<String>) {
    val height = src.size
    val width = src.maxOf { it.length }
    private val tiles = Array(height) { y -> CharArray(width) { x -> src[y].getOrElse(x) { '.' } } }

    var startX = 0; private set
    var startY = 0; private set
    var doorX = 0; private set
    var doorY = 0; private set
    val gears = HashSet<Int>()
    val gearTotal: Int
    val walkerSpawns = ArrayList<Pair<Int, Int>>()
    val hoverSpawns = ArrayList<Pair<Int, Int>>()

    init {
        for (y in 0 until height) for (x in 0 until width) {
            when (tiles[y][x]) {
                'S' -> { startX = x; startY = y }
                'D' -> { doorX = x; doorY = y }
                'o' -> gears.add(index(x, y))
                'E' -> walkerSpawns.add(x to y)
                'V' -> hoverSpawns.add(x to y)
                '#', '=', '^' -> continue
            }
            tiles[y][x] = '.'
        }
        gearTotal = gears.size
    }

    fun index(x: Int, y: Int) = y * width + x

    fun tile(x: Int, y: Int): Char =
        if (x < 0 || x >= width || y < 0 || y >= height) '.' else tiles[y][x]

    /** Les bords gauche et droit sont des murs ; le bas est un gouffre. */
    fun solid(x: Int, y: Int): Boolean =
        if (x < 0 || x >= width) true else tile(x, y) == '#'

    fun oneWay(x: Int, y: Int) = tile(x, y) == '='
    fun spike(x: Int, y: Int) = tile(x, y) == '^'
    fun standable(x: Int, y: Int) = tile(x, y) == '#' || tile(x, y) == '='
}

